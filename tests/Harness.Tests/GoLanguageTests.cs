using System.Text.Json;

namespace Harness.Tests;

/// <summary>
/// The Go axis of contract 3.1 (ADR-0055): comment density, cross-file repetition, the package
/// DSM and lint suppressions, each read through the compiled CLI on a fixture repository.
/// </summary>
public sealed class GoLanguageTests
{
    private const string Comments = "comments.go";

    private const string Duplication = "duplication.go";

    private const string Complexity = "complexity.go";

    private const string LintSuppressions = "lint-suppressions.go";

    private const string GoModule = "module example.com/app\n\ngo 1.25\n";

    [Fact]
    public void A_repository_without_go_sources_is_not_applicable_to_every_go_check()
    {
        using var repository = Fixtures.Compliant();

        foreach (var check in new[] { Comments, Duplication, Complexity, LintSuppressions })
        {
            var run = HarnessCli.RunVerbose(repository.Path, "check", "--only", check);

            Assert.Equal(0, run.ExitCode);
            Assert.True(run.OutputContains("not applicable"), run.Output);
        }
    }

    [Fact]
    public void Prose_inside_a_function_above_the_limit_is_a_blocking_violation()
    {
        var source = "package sample\n\nfunc Run() int {\n"
            + Lines(12, line => $"\t// reason {line}")
            + "\ttotal := 0\n"
            + Lines(100, line => $"\ttotal += {line}")
            + "\treturn total\n}\n";
        using var repository = Fixtures.Compliant().WriteFile("internal/sample/run.go", source).Commit();

        var run = HarnessCli.RunVerbose(repository.Path, "check", "--only", Comments);

        Assert.Equal(1, run.ExitCode);
        Assert.True(run.OutputContains("internal/sample/run.go"), run.Output);
        Assert.True(run.OutputContains("12 of 117 authored physical lines"), run.Output);
    }

    [Fact]
    public void Doc_comments_directives_raw_strings_generated_vendor_and_testdata_do_not_count()
    {
        var authored = "package sample\n\n"
            + Lines(20, line => $"// Run documents itself on line {line}.")
            + "func Run() string {\n\traw := `\n" + Lines(20, line => $"// inside the raw string {line}") + "`\n\treturn raw\n}\n\n"
            + "//go:generate stringer -type=Kind\n"
            + Lines(5, line => $"// Kind is documented on line {line}.")
            + "type Kind int\n";
        var dense = "package other\n\n" + "func Dense() {\n" + Lines(40, line => $"\t// prose {line}") + "}\n";
        using var repository = Fixtures.Compliant()
            .WriteFile("internal/sample/run.go", authored)
            .WriteFile("internal/gen/gen.go", "// Code generated by stringer; DO NOT EDIT.\n\n" + dense)
            .WriteFile("internal/sample/testdata/fixture.go", dense)
            .WriteFile("vendor/dep/dep.go", dense)
            .WriteFile("_tools/tool.go", dense)
            .Commit();

        var run = HarnessCli.RunVerbose(repository.Path, "check", "--only", Comments);

        Assert.Equal(0, run.ExitCode);
        Assert.True(run.OutputContains("outcome: passed"), run.Output);
    }

    [Fact]
    public void A_block_repeated_across_files_with_other_names_is_reported_once_with_both_places()
    {
        using var repository = Fixtures.Compliant()
            .WriteFile("internal/first/build.go", Chain("first", "Build", "v"))
            .WriteFile("internal/second/assemble.go", Chain("second", "Assemble", "w"))
            .Commit();

        var run = HarnessCli.RunVerbose(repository.Path, "check", "--only", Duplication);

        Assert.Equal(1, run.ExitCode);
        Assert.True(run.OutputContains("normalized lines"), run.Output);
        Assert.True(run.OutputContains("internal/first/build.go:"), run.Output);
        Assert.True(run.OutputContains("internal/second/assemble.go:"), run.Output);
    }

    [Fact]
    public void The_package_graph_is_measured_whole_with_the_main_package_as_composition_root()
    {
        using var repository = Packages();

        var run = HarnessCli.RunVerbose(repository.Path, "check", "--only", Complexity);

        Assert.Equal(0, run.ExitCode);
        Assert.True(run.OutputContains("limits: average reachable packages 8.00 packages · largest cyclic group size 0 packages"), run.Output);
        Assert.True(run.OutputContains("average reachable packages: 2.80 packages (14 reachable package pairs / 5 packages"), run.Output);
        Assert.True(run.OutputContains("largest cyclic group size: 0 packages (0.00% of 5 packages)"), run.Output);
        Assert.True(run.OutputContains("scope: 5 authored packages of the tracked go.mod modules (test files are not read; 1 main package [cmd/app] is the composition root)"), run.Output);
    }

    [Fact]
    public void Exceeding_the_declared_ceiling_names_the_hubs_but_never_the_main_package()
    {
        using var repository = Packages(Frame.AllPresent().Settings(
            """{ "complexity.go": { "averageReachableFiles": 2.0, "largestCyclicGroupSize": 0 } }"""));

        var run = HarnessCli.RunVerbose(repository.Path, "check", "--only", Complexity);

        Assert.Equal(1, run.ExitCode);
        Assert.True(run.OutputContains("average reachable packages 2.80 packages exceeds the 2.00 packages the standard allows"), run.Output);
        Assert.True(run.OutputContains("internal/p1: Dependencies from here reach 4 of 5 packages."), run.Output);
        Assert.False(run.OutputContains("cmd/app: Dependencies"), run.Output);
    }

    [Fact]
    public void A_go_mod_left_out_of_the_index_makes_the_dsm_incomplete_and_is_named()
    {
        using var repository = Fixtures.Compliant()
            .WriteFile("internal/p1/p1.go", "package p1\n\nfunc One() int { return 1 }\n")
            .Commit()
            .WriteFile("go.mod", GoModule);

        var run = HarnessCli.RunVerbose(repository.Path, "check", "--only", Complexity);

        Assert.Equal(2, run.ExitCode);
        Assert.True(run.OutputContains("no tracked go.mod names a module path"), run.Output);
        Assert.True(run.OutputContains("not in the index  go.mod"), run.Output);
    }

    [Fact]
    public void Nolint_without_linters_or_without_a_reason_is_blocking_and_a_justified_one_passes()
    {
        var source = "package sample\n\nfunc Run() {\n"
            + "\t_ = f() //nolint:errcheck\n"
            + "\t_ = f() //nolint\n"
            + "\t_ = f() //nolint:all // reason\n"
            + "\t_ = f() //nolint:gosec,errcheck // closing a read-only file\n"
            + "\t// nolint is discussed in prose here\n"
            + "}\n\nfunc f() error { return nil }\n";
        using var repository = Fixtures.Compliant().WriteFile("internal/sample/run.go", source).Commit();

        var run = HarnessCli.RunVerbose(repository.Path, "check", "--only", LintSuppressions);

        Assert.Equal(1, run.ExitCode);
        Assert.True(run.OutputContains("internal/sample/run.go:4: silences errcheck via //nolint:errcheck without a reason"), run.Output);
        Assert.True(run.OutputContains("internal/sample/run.go:5: silences every linter via //nolint;"), run.Output);
        Assert.True(run.OutputContains("internal/sample/run.go:6: silences every linter via //nolint:all;"), run.Output);
        Assert.False(run.OutputContains("run.go:7"), run.Output);
        Assert.False(run.OutputContains("run.go:8"), run.Output);
    }

    [Fact]
    public void A_v1_yaml_configuration_prints_repository_wide_switches_and_blocks_a_path_scoped_rule()
    {
        const string config = "linters:\n  disable-all: true\n  disable: [gosec]\nissues:\n  exclude-rules:\n"
            + "    - path: _test\\.go\n      linters:\n        - gosec\n"
            + "    - linters: [errcheck]\n      text: \"Close\"\n"
            + "    - path: internal/legacy/\n";
        using var repository = Fixtures.Compliant()
            .WriteFile("internal/sample/run.go", "package sample\n\nfunc Run() {}\n")
            .WriteFile(".golangci.yml", config)
            .Commit();

        var run = HarnessCli.RunVerbose(repository.Path, "check", "--only", LintSuppressions);

        Assert.Equal(1, run.ExitCode);
        Assert.True(run.OutputContains("every linter is switched off repository-wide via linters.disable-all: true without linters.enable at .golangci.yml:2"), run.Output);
        Assert.True(run.OutputContains("gosec is switched off repository-wide via linters.disable at .golangci.yml:3"), run.Output);
        Assert.True(run.OutputContains(".golangci.yml:6: silences gosec for path `_test\\.go` via issues.exclude-rules at one address"), run.Output);
        Assert.True(run.OutputContains("issues.exclude-rules at .golangci.yml:9 excludes errcheck matching text \"Close\" repository-wide, without a path"), run.Output);
        Assert.True(run.OutputContains("issues.exclude-rules at .golangci.yml:11 excludes every linter repository-wide, for path `internal/legacy/`"), run.Output);
    }

