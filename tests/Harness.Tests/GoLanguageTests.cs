    [Fact]
    public void Toml_and_json_configurations_are_read_by_tables_and_by_the_bcl()
    {
        const string toml = "[linters]\ndisable-all = true\nenable = [\"errcheck\"]\n\n[[issues.exclude-rules]]\npath = \"_test\\\\.go\"\nlinters = [\"gosec\"]\n";
        const string json = """{ "linters": { "disable-all": true }, "issues": { "exclude-rules": [ { "path": ".", "linters": ["errcheck"] } ] } }""";
        using var withToml = Fixtures.Compliant()
            .WriteFile("internal/sample/run.go", "package sample\n\nfunc Run() {}\n")
            .WriteFile(".golangci.toml", toml)
            .Commit();
        using var withJson = Fixtures.Compliant()
            .WriteFile("internal/sample/run.go", "package sample\n\nfunc Run() {}\n")
            .WriteFile(".golangci.json", json)
            .Commit();

        var tomlRun = HarnessCli.RunVerbose(withToml.Path, "check", "--only", LintSuppressions);
        var jsonRun = HarnessCli.RunVerbose(withJson.Path, "check", "--only", LintSuppressions);

        Assert.Equal(1, tomlRun.ExitCode);
        Assert.False(tomlRun.OutputContains("disable-all"), tomlRun.Output);
        Assert.True(tomlRun.OutputContains(".golangci.toml:5: silences gosec for path `_test\\.go` via issues.exclude-rules at one address"), tomlRun.Output);
        Assert.Equal(0, jsonRun.ExitCode);
        Assert.True(jsonRun.OutputContains("every linter is switched off repository-wide via linters.disable-all: true without linters.enable at .golangci.json"), jsonRun.Output);
        Assert.True(jsonRun.OutputContains("issues.exclude-rules at .golangci.json excludes errcheck repository-wide, for path `.`"), jsonRun.Output);
    }

    [Fact]
    public void Init_on_a_go_repository_writes_the_go_sections_and_the_vet_and_gofmt_hint()
    {
        using var repository = RepositoryFixture.CreateGitRepository()
            .WriteFile("go.mod", GoModule)
            .WriteFile("cmd/app/main.go", "package main\n\nfunc main() {}\n")
            .Commit();

        var run = HarnessCli.Run(repository.Path, "init");

        Assert.Equal(0, run.ExitCode);
        Assert.Contains("Declared go from the tracked sources", run.StandardOutput, StringComparison.Ordinal);
        Assert.Contains("`go vet ./...`", run.StandardOutput, StringComparison.Ordinal);
        Assert.Contains("`gofmt -l`", run.StandardOutput, StringComparison.Ordinal);
        Assert.False(File.Exists(repository.Absolute(".editorconfig")));

        using var document = JsonDocument.Parse(File.ReadAllText(repository.Absolute(".harness.json")));
        var root = document.RootElement;
        Assert.False(root.TryGetProperty("architecture", out _));
        Assert.Equal(["go"], root.GetProperty("applicability").EnumerateObject().Select(axis => axis.Name));
        Assert.Equal(
            ["complexity.go", "comments.go", "duplication.go", "commits"],
            root.GetProperty("settings").EnumerateObject().Select(section => section.Name));
        Assert.Equal(8.0, root.GetProperty("settings").GetProperty("complexity.go").GetProperty("averageReachableFiles").GetDouble());
        Assert.Equal(30, root.GetProperty("settings").GetProperty("duplication.go").GetProperty("windowLines").GetInt32());
        Assert.Equal("required", root.GetProperty("policy").GetProperty("lint-suppressions.go").GetString());
        Assert.False(root.GetProperty("policy").TryGetProperty("comments.csharp", out _));
    }

    [Fact]
