    }

    [Fact]
    public void Explain_describes_each_go_check_in_its_own_terms()
    {
        using var repository = Fixtures.Compliant();

        var comments = HarnessCli.Run(repository.Path, "explain", Comments);
        var duplication = HarnessCli.Run(repository.Path, "explain", Duplication);
        var complexity = HarnessCli.Run(repository.Path, "explain", Complexity);
        var suppressions = HarnessCli.Run(repository.Path, "explain", LintSuppressions);

        Assert.Equal(0, comments.ExitCode);
        Assert.True(comments.OutputContains("DO NOT EDIT") && comments.OutputContains("settings.comments.go"), comments.Output);
        Assert.Equal(0, duplication.ExitCode);
        Assert.True(duplication.OutputContains("predeclared") && duplication.OutputContains("settings.duplication.go"), duplication.Output);
        Assert.Equal(0, complexity.ExitCode);
        Assert.True(complexity.OutputContains("settings.complexity.go") && complexity.OutputContains("refuses an import cycle"), complexity.Output);
        Assert.Equal(0, suppressions.ExitCode);
        Assert.True(suppressions.OutputContains("//nolint:errcheck // reason") && suppressions.OutputContains("linters.default"), suppressions.Output);
    }

    /// <summary>main → p1 → {p2, p3} → p4: reaches 5 + 4 + 2 + 2 + 1 = 14 over 5 packages.</summary>
    private static RepositoryFixture Packages(Frame? frame = null)
        => Fixtures.Compliant(frame ?? Frame.AllPresent())
            .WriteFile("go.mod", GoModule)
            .WriteFile("cmd/app/main.go", "package main\n\nimport \"example.com/app/internal/p1\"\n\nfunc main() { _ = p1.One() }\n")
            .WriteFile("internal/p1/p1.go", "package p1\n\nimport (\n\t\"example.com/app/internal/p2\"\n\t\"example.com/app/internal/p3\"\n)\n\nfunc One() int { return p2.Two() + p3.Three() }\n")
            .WriteFile("internal/p2/p2.go", "package p2\n\nimport \"example.com/app/internal/p4\"\n\nfunc Two() int { return p4.Four() }\n")
            .WriteFile("internal/p3/p3.go", "package p3\n\nimport \"example.com/app/internal/p4\"\n\nfunc Three() int { return p4.Four() }\n")
            .WriteFile("internal/p3/p3_test.go", "package p3\n\nimport \"example.com/app/cmd/app\"\n")
            .WriteFile("internal/p4/p4.go", "package p4\n\nfunc Four() int { return 4 }\n")
            .Commit();

    private static string Chain(string package, string function, string variable)
        => $"package {package}\n\nfunc {function}(x int) int {{\n\t{variable}0 := x\n"
            + Lines(34, line => $"\t{variable}{line} := {variable}{line - 1} + {line}")
            + $"\treturn {variable}34\n}}\n";

    private static string Lines(int count, Func<int, string> line)
        => string.Concat(Enumerable.Range(1, count).Select(number => line(number) + "\n"));
}
